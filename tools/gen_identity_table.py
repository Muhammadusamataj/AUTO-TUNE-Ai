#!/usr/bin/env python3
"""Generate the frozen lower-case and NFC-domain tables used by BOTH the app (IdentityCase.java) and the server (identity_case_table.py).

Why: Java 17 implements Unicode 13, Python 3.12 Unicode 15, Android 8.x Unicode 9/10 and Android 16 Unicode 15+. Using each
runtime's own toLowerCase()/lower() made keys differ for letters added in newer Unicode versions (e.g. U+2C2F, U+A7C0,
Vithkuqi U+10570..): the app and the server then looked up different keys. Both sides now use this single frozen table.

Usage:  gen_identity_table.py          regenerate the two output files from tools/data/unicode10_simple_lowercase.tsv
        gen_identity_table.py --check  exit 1 if the committed outputs are not exactly what the table generates (used in CI)
"""
import os, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
TSV = os.path.join(ROOT, "tools", "data", "unicode10_simple_lowercase.tsv")
RANGES_TSV = os.path.join(ROOT, "tools", "data", "unicode9_assigned_ranges.tsv")
JAVA = os.path.join(ROOT, "app", "src", "main", "java", "com", "autotuneeq", "mvp", "IdentityCase.java")
PY = os.path.join(ROOT, "server", "identity_case_table.py")


def read_pairs():
    pairs = []
    with open(TSV, encoding="utf-8") as f:
        for line in f:
            if line.startswith("#") or not line.strip(): continue
            a, b = line.split()
            pairs.append((int(a, 16), int(b, 16)))
    assert pairs == sorted(pairs) and len({p[0] for p in pairs}) == len(pairs), "table must be sorted and unique"
    unsafe = {0x0A, 0x0D, 0x22, 0x5C}  # would break a Java string literal written with \\uXXXX escapes
    assert not (unsafe & {c for p in pairs for c in p}), "table contains a code point that is unsafe inside a Java \\u escape"
    return pairs


def read_ranges():
    ranges = []
    with open(RANGES_TSV, encoding="utf-8") as f:
        for line in f:
            if line.startswith("#") or not line.strip(): continue
            a, b = line.split()
            ranges.append((int(a, 16), int(b, 16)))
    assert ranges == sorted(ranges) and all(r[0] <= r[1] for r in ranges) and all(ranges[i][1] < ranges[i + 1][0] for i in range(len(ranges) - 1)), "ranges must be sorted and disjoint"
    return ranges


def java_escape(cps):
    out = []
    for cp in cps:
        if cp > 0xFFFF:
            cp -= 0x10000
            out += [0xD800 + (cp >> 10), 0xDC00 + (cp & 0x3FF)]
        else:
            out.append(cp)
    return "".join("\\u%04x" % u for u in out)


def render_java(pairs, ranges):
    frm = java_escape([p[0] for p in pairs]); to = java_escape([p[1] for p in pairs])
    rs = java_escape([r[0] for r in ranges]); re_ = java_escape([r[1] for r in ranges])
    def chunks(s):  # keep source lines short; adjacent literals are concatenated at compile time
        return "\n            + ".join('"' + s[i:i + 96 * 6] + '"' for i in range(0, len(s), 96 * 6))
    return f'''package com.autotuneeq.mvp;

/**
 * GENERATED by tools/gen_identity_table.py from tools/data/unicode10_simple_lowercase.tsv. DO NOT EDIT.
 * Frozen Unicode 10.0 simple lower-case mapping so song identity keys do not depend on the Unicode version of the
 * device (Android 8.0 .. 16), the JDK, or the Python running the server.  {len(pairs)} mappings,
 * {len(ranges)} ranges of code points assigned in Unicode 9.0 (the only text on which NFC is applied).
 */
final class IdentityCase {{
    private IdentityCase() {{ }}
    private static final String FROM = {chunks(frm)};
    private static final String TO = {chunks(to)};
    private static final String RANGE_START = {chunks(rs)};
    private static final String RANGE_END = {chunks(re_)};
    private static final int[] FROM_CP, TO_CP, START_CP, END_CP;
    static {{
        FROM_CP = FROM.codePoints().toArray();
        TO_CP = TO.codePoints().toArray();
        START_CP = RANGE_START.codePoints().toArray();
        END_CP = RANGE_END.codePoints().toArray();
    }}

    /** True when every code point of s was assigned in Unicode 9.0 (so NFC data is identical on every supported runtime). */
    static boolean nfcSafe(String s) {{
        for (int i = 0; i < s.length(); ) {{
            int cp = s.codePointAt(i); i += Character.charCount(cp);
            int k = java.util.Arrays.binarySearch(START_CP, cp);
            if (k < 0) k = -k - 2;
            if (k < 0 || cp > END_CP[k]) return false;
        }}
        return true;
    }}

    /** Simple lower-case mapping of one code point under the frozen table (identity if unmapped). */
    static int lower(int cp) {{
        int i = java.util.Arrays.binarySearch(FROM_CP, cp);
        return i >= 0 ? TO_CP[i] : cp;
    }}

    /** Table lower-casing, then final sigma folded to sigma (U+03C2 -> U+03C3) so context rules never matter. */
    static String lower(String s) {{
        StringBuilder b = new StringBuilder(s.length());
        for (int i = 0; i < s.length(); ) {{
            int cp = s.codePointAt(i); i += Character.charCount(cp);
            cp = lower(cp);
            if (cp == 0x03C2) cp = 0x03C3;
            b.appendCodePoint(cp);
        }}
        return b.toString();
    }}
}}
'''


def render_py(pairs, ranges):
    body = ",\n".join("    0x%04X: 0x%04X" % p for p in pairs)
    rbody = ",\n".join("    (0x%04X, 0x%04X)" % r for r in ranges)
    return f'''"""GENERATED by tools/gen_identity_table.py from tools/data/unicode10_simple_lowercase.tsv. DO NOT EDIT.

Frozen Unicode 10.0 simple lower-case mapping shared with the Android app (IdentityCase.java); {len(pairs)} mappings,
and {len(ranges)} ranges of code points assigned in Unicode 9.0 (NFC is applied only to text made entirely of those).
"""
import bisect

LOWER = {{
{body},
}}

ASSIGNED_9 = (
{rbody},
)
_STARTS = [r[0] for r in ASSIGNED_9]


def nfc_safe(s):
    """True when every code point was assigned in Unicode 9.0, same rule as IdentityCase.nfcSafe in the app."""
    for ch in s:
        cp = ord(ch)
        k = bisect.bisect_right(_STARTS, cp) - 1
        if k < 0 or cp > ASSIGNED_9[k][1]:
            return False
    return True


def lower(s):
    """Table lower-casing, then final sigma folded to sigma, identical to IdentityCase.lower(String) in the app."""
    out = []
    for ch in s:
        cp = LOWER.get(ord(ch), ord(ch))
        out.append(chr(0x03C3 if cp == 0x03C2 else cp))
    return "".join(out)
'''


def main():
    pairs, ranges = read_pairs(), read_ranges()
    outputs = {JAVA: render_java(pairs, ranges), PY: render_py(pairs, ranges)}
    if "--check" in sys.argv:
        bad = [p for p, text in outputs.items() if not os.path.exists(p) or open(p, encoding="utf-8").read() != text]
        for p in bad: print("OUT OF DATE:", os.path.relpath(p, ROOT))
        print("identity tables: " + ("STALE" if bad else "up to date (%d mappings, %d assigned ranges)" % (len(pairs), len(ranges))))
        return 1 if bad else 0
    for p, text in outputs.items():
        with open(p, "w", encoding="utf-8", newline="\n") as f: f.write(text)
        print("wrote", os.path.relpath(p, ROOT))
    return 0


if __name__ == "__main__":
    sys.exit(main())
